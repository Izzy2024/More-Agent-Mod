import fs from "node:fs";
import assert from "node:assert";
import { HOME, notes } from "./stubs.mjs";
const M = (await import("./main.mjs")).default;
fs.mkdirSync(HOME, { recursive: true });
const P = HOME + "/programs.json";
fs.writeFileSync(P, JSON.stringify({ programs: { aider: { run: ["my-aider"] }, "command-code": { tile: "#ff0000" } }, shells: ["zsh"] }, null, 2));
const spawned = [];
const cx = { spawn: (f) => spawned.push(f(cx)), notify: () => {} };
const m = new M(); m.init({}, cx); await Promise.all(spawned.splice(0));
assert.equal(m.onPath.omp, true); assert.equal(m.onPath.kilo, false);
m.render();
["omp", "command-code", "aider", "droid"].forEach((id) => m.selected.add(id)); m.withContinue = true;
m.addSelected(cx); await Promise.all(spawned.splice(0));
const t = JSON.parse(fs.readFileSync(P, "utf8"));
assert.deepEqual(t.programs.aider, { run: ["my-aider"] }, "no clobber");
assert.deepEqual(t.programs.omp.run, ["omp"]); assert.deepEqual(t.programs["omp-continue"].run, ["omp", "--continue"]);
assert.equal(t.programs["command-code"].tile, "#ff0000"); assert.deepEqual(t.programs["command-code"].run, ["command-code"]);
assert.ok(!t.programs["aider-continue"], "no continue when base skipped");
assert.deepEqual(t.programs["droid-continue"].run, ["droid", "--resume"]);
assert.deepEqual(t.shells, ["zsh"]);
assert.ok(fs.existsSync(P + ".more-agents.bak")); assert.ok(JSON.parse(fs.readFileSync(P + ".more-agents.bak","utf8")).programs.aider);
console.log("msg:", m.msg);
// Install-aware message: omp is on the PATH (stub exec), command-code and droid are not.
assert.match(m.msg, /omp, omp-continue: now show in the \+ menu/);
assert.match(m.msg, /Added command-code; it will show in the \+ menu once you install `command-code`/);
assert.match(m.msg, /Added droid; it will show .*`droid`/); assert.ok(!/Added droid-continue/.test(m.msg));
assert.equal(m.selected.size, 0, "selection cleared after add");
assert.equal(notes.at(-1).level, "info");
// The counter only counts what can be added.
m.selected.add("omp"); m.selected.add("kilo"); m.selected.add("gemini");
assert.deepEqual(m.selectable(), ["kilo"]); m.selected.clear();
// Tab moves focus key → name → command → key; Shift+Tab goes backwards.
let stopped = 0; const kcx = { stop_propagation: () => { stopped++; } };
m.inputs.key._fire("focus"); m.formKey({ key: "tab", modifiers: {} }, kcx); assert.equal(m.focusedField, "name");
m.formKey({ key: "tab", modifiers: { shift: true } }, kcx); assert.equal(m.focusedField, "key");
m.focusedField = "run"; m.formKey({ key: "tab", modifiers: {} }, kcx); assert.equal(m.focusedField, "key"); assert.equal(stopped, 3);
m.formKey({ key: "a", modifiers: {} }, kcx); assert.equal(stopped, 3, "other keys pass through");
m.inputs.key._set("My-Agent"); m.inputs.run._set("foo --bar"); m.addCustom(cx); await Promise.all(spawned.splice(0));
assert.deepEqual(JSON.parse(fs.readFileSync(P,"utf8")).programs["my-agent"].run, ["foo", "--bar"]);
m.render();
m.selected.add("kilo");
m.remove(["omp", "omp-continue", "aider"], cx); await Promise.all(spawned.splice(0));
assert.equal(m.selected.size, 0, "selection cleared after remove"); assert.equal(m.busy, false);
const t2 = JSON.parse(fs.readFileSync(P, "utf8"));
assert.ok(!t2.programs.omp && !t2.programs["omp-continue"]); assert.ok(t2.programs.aider, "never removes user's own");
fs.writeFileSync(P, "{ broken"); m.addSelected(cx); m.selected.add("kilo"); m.addSelected(cx); await Promise.all(spawned.splice(0));
assert.equal(fs.readFileSync(P, "utf8"), "{ broken"); console.log("broken:", m.msg.slice(0,60));
console.log("ALL OK; notifications:", notes.length);
